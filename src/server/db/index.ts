/**
 * One database handle for the whole app.
 *
 * DATABASE_URL picks the driver:
 *   postgres://user:pass@host:5432/db   PostgreSQL (production · staging · CI e2e)
 *   pglite://data/pglite                PGlite on disk (local development without Docker)
 *   memory://                           PGlite in memory (unit tests)
 *
 * PGlite is real Postgres compiled to WebAssembly. It is a dev dependency only: the production
 * image has no copy and refuses a pglite:// URL.
 */
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';
import * as schema from './schema';

export type Schema = typeof schema;
export type Db = PgDatabase<PgQueryResultHKT, Schema>;

export interface Database {
  db: Db;
  driver: 'pg' | 'pglite';
  /** Applies every migration in drizzle/ that has not run yet. Safe to call on every boot. */
  migrate(): Promise<void>;
  close(): Promise<void>;
}

/** Generated by drizzle-kit · copied into the Docker image next to dist/. */
export const MIGRATIONS = resolve('drizzle');

export async function openDatabase(url: string): Promise<Database> {
  if (/^postgres(ql)?:\/\//.test(url)) {
    const pg = (await import('pg')).default;
    const { drizzle } = await import('drizzle-orm/node-postgres');
    const { migrate } = await import('drizzle-orm/node-postgres/migrator');
    const pool = new pg.Pool({ connectionString: url, max: 10, idleTimeoutMillis: 30_000 });
    const db = drizzle(pool, { schema, casing: 'snake_case' });
    return {
      db: db as unknown as Db,
      driver: 'pg',
      migrate: () => migrate(db, { migrationsFolder: MIGRATIONS }),
      close: () => pool.end(),
    };
  }

  if (url === 'memory://' || url.startsWith('pglite://')) {
    let PGlite: typeof import('@electric-sql/pglite').PGlite;
    try {
      ({ PGlite } = await import('@electric-sql/pglite'));
    } catch {
      throw new Error('pglite:// needs the dev dependencies. In production set DATABASE_URL to a postgres:// address.');
    }
    const { drizzle } = await import('drizzle-orm/pglite');
    const { migrate } = await import('drizzle-orm/pglite/migrator');
    const dir = url === 'memory://' ? undefined : resolve(url.slice('pglite://'.length));
    if (dir) mkdirSync(dir, { recursive: true });
    const client = await PGlite.create(dir);
    const db = drizzle(client, { schema, casing: 'snake_case' });
    return {
      db: db as unknown as Db,
      driver: 'pglite',
      migrate: () => migrate(db, { migrationsFolder: MIGRATIONS }),
      close: () => client.close(),
    };
  }

  throw new Error('DATABASE_URL must start with postgres:// or pglite:// or be memory://');
}

/** Hides the password when an address is logged. */
export function safeUrl(url: string): string {
  return url.replace(/\/\/([^:/@]+):[^@]*@/, '//$1:***@');
}
