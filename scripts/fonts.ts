/**
 * npm run fonts · the site's own cut of each font into src/fonts/ (committed) and src/styles/fonts.css:
 *   <family>-core.woff2   fontsource's latin file cut to the letters the site uses (ASCII · the Latin-1
 *                         and typography it writes · ı)
 *   <family>-tr.woff2     fontsource's latin-ext file cut to the Turkish letters it holds (Ğ ğ İ Ş ş · ₺)
 * fonts.css declares the cuts with exactly the letters they hold and fontsource's own files for
 * every other letter of their range (a name in a note): the ranges never overlap, so a page
 * downloads about a hundred kilobytes in six small files and fontsource's files only for a letter
 * outside the cuts. The first paint no longer waits for the 87 kb of latin-ext a Turkish page used to
 * discover while laying out (phase 17g · Lighthouse). A unit test opens the files and checks the
 * letters · the axes · the ranges.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { create } from 'fontkit';
import subsetFont from 'subset-font';
import decompress from 'wawoff2/decompress.js';
import { FONT_CUTS, FONT_FAMILIES, parseRange, unicodeRange } from '../src/shared/fonts';

const root = resolve(import.meta.dirname, '..');
const pkg = (name: string) => join(root, 'node_modules/@fontsource-variable', name);

/** The code points a woff2 file really holds. */
export async function charset(woff2: Buffer): Promise<number[]> {
  const ttf = Buffer.from(await decompress(woff2));
  const font = create(ttf);
  if (!('characterSet' in font)) throw new Error('a font collection');
  // (fontkit lists U+FFFF for the cmap's end marker: never a letter)
  return [...font.characterSet].filter((p) => p < 0xfffe).sort((a, b) => a - b);
}

/** fontsource's own unicode-range for one of its files (its CSS names each face in a comment). */
function sourceRange(pkgName: string, axes: string, file: string): number[] {
  const css = readFileSync(join(pkg(pkgName), `${axes}.css`), 'utf8');
  const at = css.indexOf(`/* ${file} */`);
  const range = at < 0 ? null : /unicode-range:\s*([^;]+);/.exec(css.slice(at))?.[1];
  if (!range) throw new Error(`no range for ${file}`);
  return parseRange(range);
}

async function main(): Promise<void> {
  const faces: string[] = [];
  for (const fam of FONT_FAMILIES) {
    const head = `font-family:'${fam.family}';font-style:normal;font-display:swap;font-weight:${fam.weight};${fam.stretch ? `font-stretch:${fam.stretch};` : ''}`;
    const cuts = [];
    for (const cut of FONT_CUTS) {
      const sourceFile = `${fam.file}-${cut.from}-${fam.axes}-normal`;
      const source = readFileSync(join(pkg(fam.pkg), 'files', `${sourceFile}.woff2`));
      const out = await subsetFont(source, cut.text, { targetFormat: 'woff2' });
      const file = `${fam.key}-${cut.name}.woff2`;
      writeFileSync(join(root, 'src/fonts', file), out);
      cuts.push({ sourceFile, file, size: out.length, held: await charset(out), has: new Set(await charset(source)) });
    }
    // fontsource's own ranges overlap (ı is in latin and latin-ext): a letter any cut holds leaves both.
    // A range also names letters its file does not have (₺ in Geist): only the ones it has stay, so a
    // page with such a letter does not download a file for nothing.
    const taken = new Set(cuts.flatMap((c) => c.held));
    for (const c of cuts) {
      const rest = sourceRange(fam.pkg, fam.axes, c.sourceFile).filter((p) => !taken.has(p) && c.has.has(p));
      faces.push(`@font-face{${head}src:url('../../node_modules/@fontsource-variable/${fam.pkg}/files/${c.sourceFile}.woff2') format('woff2');unicode-range:${unicodeRange(rest)}}`);
      faces.push(`@font-face{${head}src:url('../fonts/${c.file}') format('woff2');unicode-range:${unicodeRange(c.held)}}`);
      console.log(`${c.file.padEnd(24)} ${String(c.size).padStart(6)} B  ${c.held.length} letters · fontsource keeps ${rest.length}`);
    }
  }
  writeFileSync(
    join(root, 'src/styles/fonts.css'),
    `/* Self-hosted variable fonts (OFL) from fontsource and the site's own cut of them · generated by npm run fonts (scripts/fonts.ts). esbuild copies each woff2 into dist with a content hash. */\n${faces.join('\n')}\n`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
